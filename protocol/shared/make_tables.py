"""Generate the results tables in paper-latex/sections/results.tex from analysis/daily.csv.

Run from the repository root:  python3 protocol/shared/make_tables.py
Writes paper-latex/tables/{throughput,cost,annualized}.tex and prints a summary.

Definitions (all over the observation window):
  throughput   Max MiB/s = protocol maximum in force (min -> max if it changed);
               p50 / mean of daily observed MiB/s; mean of daily utilization.
  cost         p50 / p90 / p99 of the daily median $/MiB; VWAP = total spend / total volume.
  annualized   p50 spot $/MiB x 365 / retention_days (protocols with a defined window).
"""
import os
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
WINDOW = ("2025-11-15", "2026-02-14")
OUT = os.path.join(ROOT, "paper-latex", "tables")

# name, dir, daily-median cost col, spend col, volume col (MiB)
P = [
    ("Polkadot", "Polkadot", "bulk_p50_cost_per_mib_usd", None, "daily_data_mib"),
    ("Ethereum", "Ethereum", "p50_cost_per_mib_usd", "daily_blob_spend_usd", "daily_data_mib"),
    ("Celestia", "Celestia", "cost_per_mib_usd_p50", "daily_da_spend_usd", "daily_blob_mib"),
    ("Espresso", "Espresso", "cost_per_mib_usd_p50", "daily_da_spend_usd", "daily_mib"),
    ("NEAR", "Near", "cost_per_mib_usd_p50", "daily_da_spend_usd", "daily_data_mib"),
    ("Avail", "Avail", "cost_per_mib_usd_p50", "daily_da_spend_usd", "daily_data_mib"),
]
PRICING = {"Polkadot": "Capacity price", "Ethereum": "Blob base fee", "Celestia": "Gas price",
           "Espresso": "Fixed fee", "NEAR": "Marginal gas", "Avail": "Per-tx average"}
# Retention in force during the window (days); None = set per node, not annualized.
RETENTION = {"NEAR": 5 * 43200 * 0.616 / 86400, "Celestia": 7.0,
             "Ethereum": 4096 * 32 * 12 / 86400, "Polkadot": 25 / 24,
             "Avail": None, "Espresso": None}
RET_LABEL = {"NEAR": "$\\sim$1.5\\,d", "Celestia": "7\\,d", "Ethereum": "$\\sim$18\\,d", "Polkadot": "25\\,h"}


def load(d):
    df = pd.read_csv(os.path.join(ROOT, "protocol", d, "analysis", "daily.csv"))
    return df[(df["_day"] >= WINDOW[0]) & (df["_day"] <= WINDOW[1])]


def fmt(x):
    if x is None or pd.isna(x):
        return "---"
    if x == 0:
        return "0"
    if abs(x) < 1e-3:
        m, e = f"{x:.1e}".split("e")
        return f"{m}$\\times$10$^{{{int(e)}}}$"
    if abs(x) < 1:
        return f"{x:.2g}" if abs(x) >= 0.01 else f"{x:.2g}"
    return f"{x:.3g}"


def main():
    os.makedirs(OUT, exist_ok=True)
    thr, cost, ann, summary = [], [], [], {}
    for name, d, ccol, scol, vcol in P:
        df = load(d)
        mx = df["max_mib_per_s"]
        mx_s = fmt(mx.iloc[0]) if mx.nunique() == 1 else f"{fmt(mx.min())}$\\to${fmt(mx.max())}"
        p50t, meant = df["actual_mib_per_s"].median(), df["actual_mib_per_s"].mean()
        util = df["utilization_pct"].mean()
        thr.append(f"{name} & {mx_s} & {fmt(p50t)} & {fmt(meant)} & {util:.2g}\\% \\\\")
        c = df[ccol].where(df[ccol] > 0).dropna()  # days without a token price have cost 0
        q = [c.quantile(x) for x in (0.5, 0.9, 0.99)]
        vwap = df[scol].sum() / df[vcol].sum() if scol else None
        star = "$^\\ast$" if name == "Polkadot" else ""
        cost.append(f"{name} & {fmt(q[0])}{star} & {fmt(q[1])} & {fmt(q[2])} & {fmt(vwap)} & {PRICING[name]} \\\\")
        r = RETENTION[name]
        if r:
            reposts = 365 / r
            ann.append((q[0] * reposts, f"{name} & {RET_LABEL[name]} & {reposts:.0f} & {fmt(q[0] * reposts)} \\\\"))
        else:
            ann.append((-1, f"{name} & node-set & --- & (spot {fmt(q[0])}) \\\\"))
        summary[name] = dict(max=mx.max(), p50=p50t, mean=meant, util=util, cost_p50=q[0],
                             cost_p90=q[1], cost_p99=q[2], vwap=vwap,
                             volume_gib=df[vcol].sum() / 1024)
    ann = [row for _, row in sorted(ann, key=lambda t: -t[0])]
    heads = {
        "throughput": ("lcccc", "\\textbf{Protocol} & \\textbf{Max MiB/s} & \\textbf{p50 MiB/s} & \\textbf{Mean MiB/s} & \\textbf{Mean util.} \\\\"),
        "cost": ("lccccc", "\\textbf{Protocol} & \\textbf{p50} & \\textbf{p90} & \\textbf{p99} & \\textbf{VWAP} & \\textbf{Measure} \\\\"),
        "annualized": ("lccc", "\\textbf{Protocol} & \\textbf{Retention} & \\textbf{Reposts/yr} & \\textbf{p50 \\$/MiB/yr} \\\\"),
    }
    for fn, rows in (("throughput", thr), ("cost", cost), ("annualized", ann)):
        spec, head = heads[fn]
        with open(os.path.join(OUT, f"{fn}.tex"), "w") as f:
            f.write("% Generated by protocol/shared/make_tables.py; do not edit by hand.\n")
            f.write(f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{head}\n\\midrule\n")
            f.write("\n".join(rows) + "\n\\bottomrule\n\\end{tabular}%\n")
    for k, v in summary.items():
        print(k, {a: (f"{b:.4g}" if b is not None else None) for a, b in v.items()})


if __name__ == "__main__":
    main()
